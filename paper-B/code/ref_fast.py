#!/usr/bin/env python3
"""Fast variant of ref_check.py (numpy only).
T is generated by BFS from one state of the eventual image (reached after w steps from an
arbitrary window state); |T| is compared with 2^(3w+2)4^M.  G_w = T with y[w] forgotten.
Group generated by Psi on closed walks: per strongly connected component, tree potentials.
usage: ref_fast.py RULE W M"""
import sys, numpy as np

def main(rule, w, M):
    n = w + 1 + M; mask = (1 << n) - 1
    tt = [(rule >> i) & 1 for i in range(8)]
    q = lambda b, c: tt[2*b + c]
    assert all(tt[4 + 2*b + c] == 1 ^ q(b, c) for b in (0, 1) for c in (0, 1))
    alpha = q(0, 0) ^ q(1, 0)
    def fb(L, C, R):
        out = np.zeros_like(C)
        for i in range(8):
            if tt[i]:
                a, b, c = i >> 2, (i >> 1) & 1, i & 1
                out |= (L if a else ~L) & (C if b else ~C) & (R if c else ~R)
        return out
    def step1(x, y, x1, y1, y2):
        Y = y | (y1 << n) | (y2 << (n + 1)); X = x | (x1 << n)
        return (Y >> 1) & mask, ((X ^ fb(Y << 1, Y, Y >> 1)) >> 1) & mask
    def step(S, r):
        ax, ay, bx, by = S & mask, (S >> n) & mask, (S >> 2*n) & mask, (S >> 3*n) & mask
        nax, nay = step1(ax, ay, *r); nbx, nby = step1(bx, by, *r)
        return nax | (nay << n) | (nbx << 2*n) | (nby << 3*n)
    inputs = [(a, b, c) for a in (0, 1) for b in (0, 1) for c in (0, 1)]
    s = np.array([(1 << w) << 3*n], dtype=np.int64)        # a = 0, b = y-flip at the front
    for _ in range(w + 1): s = step(s, (0, 0, 0))
    T = s; fr = s
    while len(fr):
        new = np.unique(np.concatenate([step(fr, r) for r in inputs]))
        fr = np.setdiff1d(new, T, assume_unique=True)
        T = np.union1d(T, fr)
    pred = 2**(3*w + 2) * 4**M
    drop = ~((1 << n) | (1 << 3*n))
    V = np.unique(T & drop); nV = len(V)
    src = []; dst = []; ths = []
    for r in inputs:
        Vn = step(V, r)
        phia = (Vn >> n) & 1; phib = (Vn >> 3*n) & 1
        ya = (V >> (n + 1)) & 1; yb = (V >> (3*n + 1)) & 1
        th = 1 | (phia << 1) | (phib << 2) | ((ya ^ alpha) << 3) | ((yb ^ alpha) << 4)
        j = np.searchsorted(V, Vn & drop); assert np.array_equal(V[j], Vn & drop)
        src.append(np.arange(nV)); dst.append(j); ths.append(th)
    src = np.concatenate(src); dst = np.concatenate(dst); ths = np.concatenate(ths)
    lab = -np.ones(nV, dtype=np.int64); ncomp = 0
    def reach(a, b, root, alive):
        seen = np.zeros(nV, bool); seen[root] = True
        while True:
            m = seen[a] & ~seen[b] & alive[b]
            if not m.any(): return seen
            seen[b[m]] = True
    while (lab < 0).any():
        root = int(np.argmax(lab < 0)); alive = lab < 0
        comp = reach(src, dst, root, alive) & reach(dst, src, root, alive)
        lab[comp] = ncomp; ncomp += 1
    intra = lab[src] == lab[dst]
    s2, d2, t2 = src[intra], dst[intra], ths[intra]
    pot = -np.ones(nV, dtype=np.int64)
    roots = np.unique(lab, return_index=True)[1]; pot[roots] = 0
    while True:
        m = (pot[s2] >= 0) & (pot[d2] < 0)
        if not m.any(): break
        pot[d2[m]] = pot[s2[m]] ^ t2[m]
    assert (pot >= 0).all()
    gens = np.unique(pot[s2] ^ t2 ^ pot[d2])
    span = {0}
    for g in gens:
        g = int(g)
        if g not in span: span |= {x ^ g for x in span}
    hol = sorted({(x >> 1) & 3 for x in span})
    print(f"rule {rule} alpha={alpha} w={w} M={M}: |T|={len(T)} (pred {pred}, ok={len(T)==pred}, 4|G|==|T|: {4*nV==len(T)}); "
          f"|G_w|={nV}; SCCs={ncomp}; group generated by Psi on closed walks has order {len(span)}; Hol={hol}", flush=True)
main(*map(int, sys.argv[1:4]))
